use std::collections::BTreeMap;
use std::path::Path;
use std::{
    fs::read_to_string,
    io::{self, BufWriter, Write},
};

use fs_err::File;
use semver::Version;
use serde::{Deserialize, Serialize};

use crate::package_id;
use crate::{
    manifest::Manifest, package_id::PackageId, package_name::PackageName, resolution::Resolve,
};

pub const LOCKFILE_NAME: &str = "wally.lock";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Lockfile {
    pub registry: String,

    #[serde(rename = "package")]
    pub packages: Vec<LockPackage>,
}

fn grab_dependencies(
    package_id: &PackageId,
    dependencies: &BTreeMap<
        package_id::PackageId,
        BTreeMap<std::string::String, package_id::PackageId>,
    >,
) -> Vec<(String, PackageId)> {
    dependencies
        .get(package_id)
        .map(|dependencies| {
            dependencies
                .iter()
                .map(|(key, value)| (key.clone(), value.clone()))
                .collect()
        })
        .unwrap_or_else(Vec::new)
}

impl Lockfile {
    pub fn from_manifest(manifest: &Manifest) -> Self {
        Self {
            registry: manifest.package.registry.clone(),
            packages: Vec::new(),
        }
    }

    pub fn from_resolve(resolve: &Resolve) -> Self {
        let mut packages = Vec::new();
        let has_locals = resolve.activated.iter().any(|id| id.local_path().is_some());

        for package_id in &resolve.activated {
            let dependencies = [
                grab_dependencies(&package_id, &resolve.shared_dependencies),
                grab_dependencies(&package_id, &resolve.server_dependencies),
                grab_dependencies(&package_id, &resolve.dev_dependencies),
            ]
            .concat();

            let dependency_realms: Vec<_> = [
                (crate::manifest::Realm::Shared, &resolve.shared_dependencies),
                (crate::manifest::Realm::Server, &resolve.server_dependencies),
                (crate::manifest::Realm::Dev, &resolve.dev_dependencies),
            ]
            .iter()
            .flat_map(|(realm, graph)| {
                grab_dependencies(package_id, graph)
                    .into_iter()
                    .map(move |(alias, id)| (*realm, alias, id))
            })
            .collect();
            packages.push(if let Some(path) = package_id.local_path() {
                LockPackage::Local(LocalLockPackage {
                    name: package_id.name().clone(),
                    path: path.into(),
                    realm: resolve.metadata[package_id].realm,
                    origin_realms: resolve.metadata[package_id].origin_realms.clone(),
                    dependencies,
                    dependency_realms,
                })
            } else {
                LockPackage::Registry(RegistryLockPackage {
                    name: package_id.name().clone(),
                    version: package_id.version().unwrap().clone(),
                    checksum: None,
                    dependencies,
                    dependency_realms: if has_locals {
                        Some(dependency_realms)
                    } else {
                        None
                    },
                })
            });
        }

        Self {
            registry: resolve.registry.clone(),
            packages,
        }
    }

    pub fn load(project_path: &Path) -> anyhow::Result<Option<Self>> {
        let lockfile_path = project_path.join(LOCKFILE_NAME);
        let contents = match read_to_string(&lockfile_path) {
            Ok(contents) => contents,
            Err(err) => {
                if err.kind() == io::ErrorKind::NotFound {
                    return Ok(None);
                } else {
                    return Err(err.into());
                }
            }
        };
        let lockfile: Self = toml::from_str(&contents)?;
        anyhow::ensure!(
            !lockfile
                .packages
                .iter()
                .any(|package| matches!(package, LockPackage::Git(_))),
            "Git lockfile entries are not supported. Use registry or caret-path dependencies."
        );
        Ok(Some(lockfile))
    }

    pub fn save(&self, project_path: &Path) -> anyhow::Result<()> {
        let lockfile_path = project_path.join(LOCKFILE_NAME);

        let mut file = BufWriter::new(File::create(lockfile_path)?);
        writeln!(file, "# This file is automatically @generated by Wally.")?;
        writeln!(file, "# It is not intended for manual editing.")?;
        writeln!(
            file,
            "registry = {}",
            toml::Value::String(self.registry.clone())
        )?;
        writeln!(file, "")?;

        for lock_package in self.packages.iter() {
            writeln!(file, "[[package]]")?;

            match lock_package {
                LockPackage::Registry(registry_lock_package) => {
                    writeln!(file, "name = \"{}\"", registry_lock_package.name)?;
                    writeln!(file, "version = \"{}\"", registry_lock_package.version)?;

                    if let Some(checksum) = &registry_lock_package.checksum {
                        writeln!(file, "checksum = {}", toml::Value::String(checksum.clone()))?;
                    }

                    if let Some(edges) = &registry_lock_package.dependency_realms {
                        writeln!(
                            file,
                            "dependency_realms = {}",
                            toml::Value::try_from(edges)?
                        )?;
                    }
                    if registry_lock_package.dependencies.len() == 0 {
                        writeln!(file, "dependencies = []")?;
                    } else {
                        writeln!(file, "dependencies = [")?;
                        for dependency in registry_lock_package.dependencies.iter() {
                            writeln!(file, "\t[\"{}\", \"{}\"],", dependency.0, dependency.1)?;
                        }
                        writeln!(file, "]")?;
                    }
                }
                LockPackage::Local(local) => {
                    // Use TOML serialization for escaping source paths and dependency aliases.
                    write!(file, "{}", toml::to_string(local)?)?;
                }
                LockPackage::Git(git_lock_package) => {
                    writeln!(file, "name = \"{}\"", git_lock_package.name)?;
                    writeln!(file, "rev = \"{}\"", git_lock_package.rev)?;
                    writeln!(file, "commit = \"{}\"", git_lock_package.commit)?;

                    if git_lock_package.dependencies.len() == 0 {
                        writeln!(file, "dependencies = []")?;
                    } else {
                        writeln!(file, "dependencies = [")?;
                        for dependency in git_lock_package.dependencies.iter() {
                            writeln!(file, "\t\"{}\",", dependency)?;
                        }
                        writeln!(file, "]")?;
                    }
                }
            }

            writeln!(file, "")?;
        }

        file.flush()?;

        Ok(())
    }

    /// Compare graph semantics, not incidental TOML ordering or optional checksums.
    pub fn graph_matches(&self, resolve: &Resolve) -> bool {
        fn normalized(lockfile: &Lockfile) -> Vec<LockPackage> {
            let mut packages = lockfile.packages.clone();
            for package in &mut packages {
                match package {
                    LockPackage::Registry(package) => {
                        package.checksum = None;
                        package.dependencies.sort();
                        if let Some(edges) = &mut package.dependency_realms {
                            edges.sort();
                        }
                    }
                    LockPackage::Local(package) => {
                        package.dependencies.sort();
                        package.dependency_realms.sort();
                    }
                    LockPackage::Git(_) => {}
                }
            }
            packages.sort_by_key(|package| match package {
                LockPackage::Registry(package) => {
                    PackageId::new(package.name.clone(), package.version.clone()).to_string()
                }
                LockPackage::Local(package) => {
                    PackageId::local(package.name.clone(), package.path.clone()).to_string()
                }
                LockPackage::Git(package) => package.name.clone(),
            });
            packages
        }
        normalized(self) == normalized(&Self::from_resolve(resolve))
    }

    pub fn as_ids(&self) -> impl Iterator<Item = PackageId> + '_ {
        self.packages
            .iter()
            .filter_map(|lock_package| match lock_package {
                LockPackage::Registry(lock_package) => Some(PackageId::new(
                    lock_package.name.clone(),
                    lock_package.version.clone(),
                )),
                LockPackage::Local(local) => {
                    Some(PackageId::local(local.name.clone(), local.path.clone()))
                }
                // Persisted Git entries are rejected by load, not deferred to a panic.
                LockPackage::Git(_) => None,
            })
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum LockPackage {
    Registry(RegistryLockPackage),
    Local(LocalLockPackage),
    Git(GitLockPackage),
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LocalLockPackage {
    pub name: PackageName,
    pub path: String,
    pub realm: crate::manifest::Realm,
    pub origin_realms: std::collections::BTreeSet<crate::manifest::Realm>,
    pub dependencies: Vec<(String, PackageId)>,
    #[serde(default)]
    pub dependency_realms: Vec<(crate::manifest::Realm, String, PackageId)>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RegistryLockPackage {
    pub name: PackageName,
    pub version: Version,
    pub checksum: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub dependency_realms: Option<Vec<(crate::manifest::Realm, String, PackageId)>>,

    #[serde(default)]
    pub dependencies: Vec<(String, PackageId)>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GitLockPackage {
    pub name: String,
    pub rev: String,
    pub commit: String,

    #[serde(default)]
    pub dependencies: Vec<PackageId>,
}
